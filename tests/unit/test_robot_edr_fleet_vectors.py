"""Run the shared `robodr.fleet` contract vectors against the fleet routes.

`tests/data/robot_edr/fleet_vectors/` is a copy of the RoboDR repository's
`docs/contracts/fixtures/fleet/` (`manifest.json`, `cases/`, `tokens/` and
`keys/`), generated by `cargo run -p robodr-fleet --example fleet_vectors`
and replayed there through the reference SOC
(`crates/robodr-fleet/tests/common/soc.rs`). Of the fixed-seed **test** key
files only the public halves are copied, plus the two SOC secret files
(`soc.key`, `soc-approval.key`): the SOC side signs answers with them, which
is what the vectors check. They are test keys and must never be registered
anywhere real.

Every case starts from an empty workspace holding the SOC fleet and approval
keys and the case's tokens and publications; its requests run in order with
the server clock set per request. Every `200` must be byte-identical to the
reference answer (Ed25519 is deterministic), which is stricter than the
manifest's comparison rule.

The SOC refuses the vectors' SOC keys as real SOC keys and keeps a
registered key id forever (`key_registry`): this suite stores the SOC keys
directly (an approval key's secret is never imported through the API) and
forgets the vectors' robot keys between cases.
"""


@pytest.fixture
def local_replay_cache(monkeypatch: pytest.MonkeyPatch) -> None:
    """Use the per-process replay cache so each case can start empty.

    The vectors reuse request headers across cases (each case is a fresh SOC);
    the Redis-backed path is covered by test_robot_edr_fleet.py.
    """

    async def _no_redis() -> Any:
        raise RuntimeError("redis disabled for the vectors")

    monkeypatch.setattr(fleet_replay, "get_redis_client", _no_redis)
    monkeypatch.setattr(fleet_throttle, "get_redis_client", _no_redis)


def _vector_key_ids() -> list[str]:
    return [entry["key_id"] for entry in MANIFEST["keys"]]


def _admin(ws: Workspace) -> Role:
    return Role(
        type="service_account",
        service_id="autosecops-api",
        service_account_id=uuid.uuid4(),
        workspace_id=ws.id,
        organization_id=ws.organization_id,
        scopes=ADMIN_SCOPES,
    )


async def _new_workspace(org_id: uuid.UUID) -> Workspace:
    ws = Workspace(
        id=uuid.uuid4(), name=f"fleet-{uuid.uuid4().hex[:8]}", organization_id=org_id
    )
    async with get_async_session_bypass_rls_context_manager() as session:
        session.add(ws)
        await session.commit()
    return ws


async def _drop_workspace(ws: Workspace) -> None:
    """Drop the case's SOC, and forget the vectors' keys (each case is fresh)."""
    async with get_async_session_bypass_rls_context_manager() as session:
        await session.execute(delete(Workspace).where(Workspace.id == ws.id))
        await session.execute(
            delete(RobotKeyRegistry).where(
                RobotKeyRegistry.key_id.in_(_vector_key_ids())
            )
        )
        await session.commit()


async def _robot(session: Any, ws: Workspace, robot_id: str) -> Robot:
    robot = Robot(workspace_id=ws.id, robot_id=robot_id)
    session.add(robot)
    await session.flush()
    return robot


async def _setup_case(ws: Workspace, setup: dict[str, Any]) -> None:
    """The SOC keys, the case's tokens and its publications (served verbatim)."""
    async with get_async_session_bypass_rls_context_manager() as session:
        service = RobotFleetService(session, role=_admin(ws))
        for kind, path in (
            (FleetSocKeyKind.FLEET, "keys/soc.key"),
            (FleetSocKeyKind.APPROVAL, "keys/soc-approval.key"),
        ):
            key_file = wire.parse_key_file((VECTORS / path).read_text())
            assert key_file.seed is not None
            session.add(
                RobotFleetSocKey(
                    workspace_id=ws.id,
                    kind=kind.value,
                    key_id=key_file.key_id,
                    public_key=key_file.public_key,
                    encrypted_seed=encrypt_secret(key_file.seed),
                    custody=FleetSocKeyCustody.ONLINE.value,
                    status=FleetSocKeyStatus.ACTIVE.value,
                )
            )
        soc_public = wire.parse_key_file((VECTORS / "keys/soc.key.pub").read_text())
        for token_file in setup.get("tokens", []):
            token = wire.parse_token((VECTORS / token_file).read_text())
            assert token.verify(soc_public.public_key), token_file
            service.store_token(token.payload, robot_fk=None)
        robots: dict[str, Robot] = {}

        async def robot(robot_id: str) -> Robot:
            if robot_id not in robots:
                robots[robot_id] = await _robot(session, ws, robot_id)
            return robots[robot_id]

        for robot_id, path in setup.get("rings", {}).items():
            body = (VECTORS / path).read_bytes()
            info = wire.parse_ring(wire.parse_envelope(body, wire.T_RING).payload)
            session.add(
                RobotFleetRing(
                    workspace_id=ws.id,
                    robot_fk=(await robot(robot_id)).id,
                    serial=info.serial,
                    ring=info.ring,
                    target_version=info.target_version,
                    bundle_sha256=info.bundle_sha256,
                    min_version=info.min_version,
                    issued_at_ms=info.issued_at_ms,
                    expires_at_ms=info.expires_at_ms,
                    envelope=body,
                )
            )
        for robot_id, path in setup.get("offers", {}).items():
            body = (VECTORS / path).read_bytes()
            offer = wire.parse_offer(body)
            locked = check_locked_profile(offer.profile)
            session.add(
                RobotFleetProfileOffer(
                    workspace_id=ws.id,
                    robot_fk=(await robot(robot_id)).id,
                    profile_version=offer.profile_version,
                    platform=locked.platform,
                    digest=offer.digest,
                    body=body,
                )
            )
        for digest_hex, path in setup.get("approvals", {}).items():
            body = (VECTORS / path).read_bytes()
            approval = wire.parse_approval(
                wire.parse_envelope(body, wire.T_APPROVAL).payload
            )
            assert approval.profile_digest == f"sha256:{digest_hex}"
            session.add(
                RobotFleetApproval(
                    workspace_id=ws.id,
                    approval_id=approval.approval_id,
                    robot_fk=(await robot(approval.robot_id)).id,
                    platform=approval.platform,
                    profile_digest=approval.profile_digest,
                    profile_version=approval.profile_version,
                    status=FleetApprovalStatus.SIGNED.value,
                    validity_ms=approval.expires_at_ms - approval.issued_at_ms,
                    issued_at_ms=approval.issued_at_ms,
                    expires_at_ms=approval.expires_at_ms,
                    envelope=body,
                )
            )
        trust_root = wire.parse_key_file(
            (VECTORS / "keys/trust-root.key.pub").read_text()
        )
        for platform, path in setup.get("revocations", {}).items():
            body = (VECTORS / path).read_bytes()
            parsed = parse_revocation_list(body)
            assert parsed.platform == platform
            session.add(
                RobotFleetRevocationList(
                    workspace_id=ws.id,
                    platform=platform,
                    serial=parsed.serial,
                    list_digest=parsed.list_digest,
                    signer_key_id=parsed.signer_key_id,
                    signature_checked=parsed.verify(trust_root.public_key),
                    trust_root_key_id=trust_root.key_id,
                    body=body,
                )
            )
        await session.commit()


def _mismatch(expected: dict[str, Any], response: httpx.Response) -> str | None:
    """How ``response`` differs from the vector's (manifest comparison rule)."""
    if response.status_code != expected["status"]:
        return (
            f"status {response.status_code} != {expected['status']}: "
            f"{response.text[:300]}"
        )
    if expected["status"] != 200:
        code = response.json().get("code")
        if code != expected["body"]["code"]:
            return f"code {code!r} != {expected['body']['code']!r}"
        return None
    if hashlib.sha256(response.content).hexdigest() != expected["body_sha256"]:
        return f"body differs from the reference answer: {response.content[:300]!r}"
    if envelope := expected.get("envelope"):
        opened = wire.parse_envelope(response.content, envelope["type"])
        if opened.signers != envelope["signed_by"]:
            return f"signers {opened.signers} != {envelope['signed_by']}"
        if json.loads(opened.payload) != envelope["payload"]:
            return "payload differs"
    return None


async def _run_request(
    client: httpx.AsyncClient, request_path: str, monkeypatch: pytest.MonkeyPatch
) -> str | None:
    base = VECTORS / request_path
    request = json.loads(base.with_name(base.name + ".request.json").read_text())
    expected = json.loads(base.with_name(base.name + ".response.json").read_text())
    body = (base.parent / request["body_file"]).read_bytes()
    assert hashlib.sha256(body).hexdigest() == request["body_sha256"]
    if expected["status"] == 200:
        reference = (base.parent / expected["body_file"]).read_bytes()
        assert hashlib.sha256(reference).hexdigest() == expected["body_sha256"]
    server_time = request["server_time_ms"]
    monkeypatch.setattr(fleet, "now_ms", lambda: server_time)
    target: str = request["target"]
    assert target.startswith(f"{BASE_PATH}/")
    # Behind Caddy the API sees the target without its base path (stripped).
    response = await client.request(
        request["method"],
        target.removeprefix(BASE_PATH),
        content=body,
        headers=[(name, value) for name, value in request["headers"]],
    )
    return _mismatch(expected, response)


@pytest.mark.usefixtures("local_replay_cache")
async def test_every_fleet_contract_vector(
    svc_organization: Organization, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Each case runs in a fresh workspace (keys are unique across the SOC)."""
    app = FastAPI()
    app.include_router(fleet_router)
    transport = httpx.ASGITransport(app=app)
    mismatches: list[str] = []
    for case in MANIFEST["cases"]:
        await fleet_replay.clear_local()
        await fleet_throttle.clear_local()
        workspace = await _new_workspace(svc_organization.id)
        try:
            await _setup_case(workspace, case.get("setup", {}))
            async with httpx.AsyncClient(
                transport=transport, base_url="http://test"
            ) as client:
                for request_path in case["requests"]:
                    if problem := await _run_request(client, request_path, monkeypatch):
                        mismatches.append(f"{request_path}: {problem}")
        finally:
            await _drop_workspace(workspace)
    assert not mismatches, "\n".join(mismatches)
    assert len(MANIFEST["cases"]) >= 17


def test_manifest_keys_match_the_copied_files() -> None:
    """Every manifest key id is the id derived from its copied public file."""
    for entry in MANIFEST["keys"]:
        public = wire.parse_key_file((VECTORS / (entry["file"] + ".pub")).read_text())
        assert public.key_id == entry["key_id"]
    soc = wire.parse_key_file((VECTORS / "keys/soc.key").read_text())
    approval = wire.parse_key_file((VECTORS / "keys/soc-approval.key").read_text())
    assert soc.seed is not None and approval.seed is not None
    assert soc.key_id != approval.key_id

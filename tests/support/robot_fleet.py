async def issue(soc: Soc, robot_uuid: uuid.UUID, hours: int = 24) -> wire.ParsedToken:
    async with get_async_session_context_manager() as session:
        issued = await soc.fleet(soc.alice, session).issue_token(
            robot_uuid, FleetTokenCreate(validity_hours=hours)
        )
    assert issued.status == "active"
    return wire.parse_token(issued.token)


async def enroll(
    soc: Soc,
    robot_api: httpx.AsyncClient,
    robot_uuid: uuid.UUID,
    robot_id: str = "ugv-101",
    site: str | None = "lab-9",
) -> SimRobot:
    token = await issue(soc, robot_uuid)
    sim = SimRobot.new(robot_id, site)
    response = await robot_api.post(
        "/robot-edr/v2/fleet/enroll",
        content=sim.enroll_body(token),
        headers={"Content-Type": "application/json"},
    )
    assert response.status_code == 200, response.text
    return sim


async def enrolled(
    soc: Soc, robot_api: httpx.AsyncClient
) -> tuple[uuid.UUID, SimRobot]:
    robot_uuid = await setup_keys_and_robot(soc)
    return robot_uuid, await enroll(soc, robot_api, robot_uuid)


async def signed_post(
    robot_api: httpx.AsyncClient, sim: SimRobot, path: str, body: bytes
) -> httpx.Response:
    return await robot_api.post(
        path, content=body, headers=sim.auth_headers("POST", path, body)
    )


async def signed_get(
    robot_api: httpx.AsyncClient, sim: SimRobot, path: str
) -> httpx.Response:
    return await robot_api.get(path, headers=sim.auth_headers("GET", path))


def revocation_list(
    root: wire.SigningKey,
    *,
    platform: str = "ugv-x1",
    serial: int = 2,
    digests: list[str] | None = None,
) -> str:
    """A ``robodr-profile-revocations/v2`` list signed by ``root``."""
    body = {
        "format": "robodr-profile-revocations/v2",
        "serial": serial,
        "issued_at": 1_700_000_000,
        "platform": platform,
        "revoked_digests": digests or [],
        "revoked_keys": [],
    }
    message = b"robodr-profile-revocations/v2\x00" + wire.dumps_compact(body)
    signed = {
        **body,
        "signature": {
            "algorithm": "ed25519",
            "key_id": root.key_id,
            "signature_hex": root.sign(message).hex(),
        },
    }
    return json.dumps(signed)

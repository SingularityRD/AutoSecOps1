def new_key() -> wire.SigningKey:
    return wire.SigningKey.from_seed(secrets.token_bytes(32))


def now_ms() -> int:
    return int(time.time() * 1000)


@dataclass
class SimRobot:
    robot_id: str
    site: str | None
    uplink: wire.SigningKey
    finding: wire.SigningKey
    blackbox: wire.SigningKey
    workspace: str = ""

    @classmethod
    def new(cls, robot_id: str, site: str | None) -> SimRobot:
        return cls(robot_id, site, new_key(), new_key(), new_key())

    def enroll_body(
        self, token: wire.ParsedToken, request_id: str | None = None
    ) -> bytes:
        p = token.payload
        self.workspace = p.workspace
        keys = [
            {
                "role": role,
                "key_id": k.key_id,
                "public_hex": k.public_key.hex(),
                "fingerprint": wire.fingerprint(k.public_key),
            }
            for role, k in (
                ("uplink", self.uplink),
                ("finding", self.finding),
                ("blackbox", self.blackbox),
            )
        ]
        payload = wire.dumps_compact(
            {
                "format": wire.ENROLL_REQUEST_FORMAT,
                "request_id": request_id or f"rfe1-{secrets.token_hex(16)}",
                "token_id": p.token_id,
                "workspace": p.workspace,
                "robot_id": self.robot_id,
                "site": self.site,
                "created_at_ms": now_ms(),
                "agentd_version": "0.2.0",
                "profile_digest": None,
                "keys": keys,
            }
        )
        signed = json.loads(
            wire.sign_envelope(
                wire.T_ENROLL_REQUEST,
                payload,
                [self.uplink, self.finding, self.blackbox],
            )
        )
        mac = wire.token_mac(bytes.fromhex(p.nonce), p.token_id, payload).hex()
        signed["mac"] = {"alg": "hmac-sha256", "token_id": p.token_id, "mac": mac}
        return wire.dumps_compact(signed) + b"\n"

    def rotate_body(self, rotation_id: str, new: wire.SigningKey) -> bytes:
        """A ``finding`` key rotation to ``new`` (signed by old, then new)."""
        payload = wire.dumps_compact(
            {
                "format": wire.ROTATE_REQUEST_FORMAT,
                "rotation_id": rotation_id,
                "workspace": self.workspace,
                "robot_id": self.robot_id,
                "role": "finding",
                "old_key_id": self.finding.key_id,
                "old_fingerprint": wire.fingerprint(self.finding.public_key),
                "new_key_id": new.key_id,
                "new_public_hex": new.public_key.hex(),
                "new_fingerprint": wire.fingerprint(new.public_key),
                "created_at_ms": now_ms(),
            }
        )
        return wire.sign_envelope(wire.T_ROTATE_REQUEST, payload, [self.finding, new])

    def cancel_body(self, rotation_id: str, new_key_id: str, digest: str) -> bytes:
        """Cancel a ``finding`` key rotation (signed by the old key only)."""
        payload = wire.dumps_compact(
            {
                "format": wire.CANCEL_REQUEST_FORMAT,
                "rotation_id": rotation_id,
                "request_digest": digest,
                "workspace": self.workspace,
                "robot_id": self.robot_id,
                "role": "finding",
                "old_key_id": self.finding.key_id,
                "new_key_id": new_key_id,
                "created_at_ms": now_ms(),
            }
        )
        return wire.sign_envelope(wire.T_CANCEL_REQUEST, payload, [self.finding])

    def auth_headers(
        self,
        method: str,
        path: str,
        body: bytes = b"",
        key: wire.SigningKey | None = None,
    ) -> dict[str, str]:
        key = key or self.uplink
        ts = now_ms()
        message = wire.request_message(method, f"/api{path}", key.key_id, ts, body)
        headers = {
            "X-RoboDR-Key-Id": key.key_id,
            "X-RoboDR-Timestamp": str(ts),
            "X-RoboDR-Signature": key.sign(message).hex(),
        }
        if method == "POST":
            headers["Content-Type"] = "application/json"
        return headers



async def _user(email: str) -> uuid.UUID:
    user = User(
        email=email,
        hashed_password="hashed_password_for_testing",
        is_active=True,
        is_verified=True,
        is_superuser=False,
    )
    async with get_async_session_context_manager() as session:
        session.add(user)
        await session.commit()
        return user.id


async def new_soc(organization: Organization) -> tuple[Soc, list[uuid.UUID]]:
    """A workspace with two platform users and a service role, all admins."""
    ws = Workspace(
        id=uuid.uuid4(),
        name=f"fleet-{uuid.uuid4().hex[:8]}",
        organization_id=organization.id,
    )
    async with get_async_session_context_manager() as session:
        session.add(ws)
        await session.commit()
    suffix = uuid.uuid4().hex[:8]
    alice_id = await _user(f"alice-{suffix}@example.com")
    bob_id = await _user(f"bob-{suffix}@example.com")

    def role(user_id: uuid.UUID | None) -> Role:
        return Role(
            type="user" if user_id else "service",
            service_id="autosecops-api",
            user_id=user_id,
            workspace_id=ws.id,
            organization_id=ws.organization_id,
            scopes=FLEET_SCOPES,
        )

    soc = Soc(workspace=ws, alice=role(alice_id), bob=role(bob_id), service=role(None))
    return soc, [alice_id, bob_id]


async def drop_soc(soc: Soc, user_ids: list[uuid.UUID]) -> None:
    async with get_async_session_context_manager() as session:
        await session.execute(delete(Workspace).where(Workspace.id == soc.workspace.id))
        for user_id in user_ids:
            await session.execute(delete(User).where(User.__table__.c.id == user_id))
        await session.commit()



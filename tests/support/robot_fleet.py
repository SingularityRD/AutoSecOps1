async def setup_keys(soc: Soc) -> None:
    """An active fleet key and an active (online) approval key.

    The approval key is generated by Alice and activated by Bob: activation
    is a two-person step.
    """
    async with get_async_session_context_manager() as session:
        alice = soc.fleet(soc.alice, session)
        await alice.create_fleet_key(FleetSocKeyCreate(kind=FleetSocKeyKind.FLEET))
        approval = await alice.create_approval_key(
            FleetSocKeyCreate(
                kind=FleetSocKeyKind.APPROVAL, custody=FleetSocKeyCustody.ONLINE
            )
        )
        await soc.fleet(soc.bob, session).activate_approval_key(approval)


async def setup_keys_and_robot(soc: Soc, robot_id: str = "ugv-101") -> uuid.UUID:
    await setup_keys(soc)

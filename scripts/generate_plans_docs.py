"""Generate docs/self-hosting/plans.mdx from autosecops/licensing/plans.py.

Usage:
    python scripts/generate_plans_docs.py          # rewrite the page
    python scripts/generate_plans_docs.py --check  # exit 1 if the page drifted

A unit test runs the check, so the page cannot drift from the plan presets.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from autosecops.licensing.plans import (
    FREE_ENTITLEMENTS,
    PLAN_ENTITLEMENTS,
    PLAN_ORDER,
    PlanGrant,
    minimum_plan,
    plan_duration,
    plan_label,
)
from autosecops.licensing.types import LicenseGrant, LicenseLimits, LicensePlan
from autosecops.tiers.enums import Entitlement

ROOT_DIR = Path(__file__).resolve().parent.parent
PAGE_PATH = ROOT_DIR / "docs" / "self-hosting" / "plans.mdx"
AUTO_GENERATED_COMMENT = (
    "{/* Auto-generated by scripts/generate_plans_docs.py from"
    " autosecops/licensing/plans.py; do not edit by hand. */}"
)

GRANT_DOCS: dict[PlanGrant, tuple[str, str | None]] = {
    Entitlement.CUSTOM_REGISTRY: (
        "Custom registry repositories",
        "/custom-actions/custom-registry",
    ),
    Entitlement.WORKSPACE_CHAT: ("Workspace chat", "/agents/workspace-chat"),
    Entitlement.CASE_ADDONS: (
        "Case add-ons: tasks, dropdowns, durations, sub-cases, closure"
        " requirements, linked rows, correlations, and case, task, and comment"
        " triggers",
        "/automations/cases/tasks",
    ),
    Entitlement.AGENT_ADDONS: (
        "Agent add-ons: agent mentions, agent and skill folders and tags",
        "/automations/cases/agent-mentions",
    ),
    Entitlement.FORMS: ("Forms", "/automations/triggers/forms"),
    Entitlement.GIT_SYNC: ("Git sync", "/manage-platform/git-sync"),
    Entitlement.SERVICE_ACCOUNTS: (
        "Service accounts and REST API keys",
        "/manage-platform/service-accounts",
    ),
    Entitlement.RBAC_ADDONS: (
        "Custom roles, groups, and SCIM",
        "/manage-platform/custom-roles",
    ),
    Entitlement.MULTI_WORKSPACE: ("More than one workspace", None),
    Entitlement.EXTERNAL_SECRET_STORES: (
        "External secret stores",
        "/automations/core-concepts/external-secret-stores",
    ),
    Entitlement.AGENT_CHANNELS: ("Agent channels", "/agents/channels"),
    Entitlement.SEMANTIC_SEARCH: (
        "Vector search in tables",
        "/automations/tables#vector-search",
    ),
    Entitlement.WATCHTOWER: ("Watchtower agent monitoring", None),
    Entitlement.TUNNELS: ("Tunnels", "/manage-platform/tunnels"),
    Entitlement.ROBOT_EDR: ("Robot EDR", "/tools/robodr"),
    Entitlement.AGENT_RUNTIME_PREVIEW: (
        "Agent runtime preview: agent backends other than the built-in one",
        None,
    ),
    LicenseGrant.MULTI_TENANT: (
        "Multi-tenant mode",
        "/self-hosting/license#multi-tenant-deployments",
    ),
}
"""Display name and docs link, if a page exists, for every grant."""

_LIMIT_LABELS: dict[str, str] = {
    "max_users": "Active users",
    "max_workspaces": "Workspaces",
    "max_organizations": "Organizations",
    "max_concurrent_workflows": "Concurrent workflow runs",
    "max_concurrent_actions": "Concurrent actions",
    "max_action_executions_per_workflow": "Action executions per workflow run",
}


def _grant_order(grant: PlanGrant) -> tuple[int, str]:
    return (PLAN_ORDER.index(minimum_plan(grant)), grant.value)


def _all_grants() -> list[PlanGrant]:
    grants: list[PlanGrant] = [*Entitlement, *LicenseGrant]
    return sorted(grants, key=_grant_order)


def _includes(plan: LicensePlan, grant: PlanGrant) -> bool:
    if grant in FREE_ENTITLEMENTS:
        return True
    return grant in PLAN_ENTITLEMENTS[plan]


def _duration_days(plan: LicensePlan) -> str:
    if plan is LicensePlan.COMMUNITY:
        return "No license"
    return f"{plan_duration(plan).days} days"


def render() -> str:
    """Return the full page content."""
    plans = PLAN_ORDER
    lines = [
        "---",
        "title: Plans and entitlements",
        'description: "The entitlements each AutoSecOps plan includes, the'
        " smallest plan that unlocks each feature, and the default license term"
        ' and limits."',
        'keywords: ["plans", "entitlements", "team", "business", "enterprise",'
        ' "mssp", "pricing", "license"]',
        "---",
        "",
        AUTO_GENERATED_COMMENT,
        "",
        "Each plan includes every entitlement of the plans before it.",
        "A [license key](/self-hosting/license) grants exactly the entitlements"
        " it lists, so a license can also add single entitlements to a plan.",
        "Community is the free feature set and needs no license.",
        "To buy or change a plan, contact"
        " [info@singularityrd.com](mailto:info@singularityrd.com).",
        "",
        "## Entitlements by plan",
        "",
        "| Feature | Key | Minimum plan | "
        + " | ".join(plan_label(p) for p in plans)
        + " |",
        "| :------ | :-- | :----------- | " + " | ".join(":-:" for _ in plans) + " |",
    ]
    for grant in _all_grants():
        name, link = GRANT_DOCS[grant]
        feature = f"[{name}]({link})" if link else name
        cells = ["Yes" if _includes(p, grant) else "-" for p in plans]
        lines.append(
            f"| {feature} | `{grant.value}` |"
            f" {plan_label(minimum_plan(grant))} | " + " | ".join(cells) + " |"
        )
    lines.extend(
        [
            "",
            "Enterprise includes every entitlement, including ones added in later"
            " releases.",
            "MSSP adds the `multi_tenant` deployment grant to Enterprise.",
            "`agent_runtime_preview` also turns on without a license when a"
            " package that registers an agent backend is installed.",
            "A Pilot license includes the Enterprise entitlements for"
            f" {plan_duration(LicensePlan.PILOT).days} days.",
            "",
            "## Default license term",
            "",
            "| Plan | Default term |",
            "| :--- | :----------- |",
        ]
    )
    for plan in (*plans, LicensePlan.PILOT):
        lines.append(f"| {plan_label(plan)} | {_duration_days(plan)} |")
    lines.extend(
        [
            "",
            "## Default limits",
            "",
            "No plan sets a limit by default.",
            "A license sets limits per contract; a limit the license does not set"
            " is unlimited.",
            "See [License limits](/self-hosting/license#license-limits) for how"
            " AutoSecOps enforces them.",
            "",
            "| Limit | Key | Default |",
            "| :---- | :-- | :------ |",
        ]
    )
    defaults = LicenseLimits().model_dump()
    for key in LicenseLimits.model_fields:
        value = defaults[key]
        default = "Unlimited" if value is None else str(value)
        lines.append(f"| {_LIMIT_LABELS[key]} | `{key}` | {default} |")
    lines.extend(
        [
            "",
            "## Related pages",
            "",
            "- See [License key](/self-hosting/license) to install a license and"
            " check what it grants.",
            "",
        ]
    )
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit with status 1 if the page differs from the generated content",
    )
    args = parser.parse_args(argv)
    content = render()
    if args.check:
        current = PAGE_PATH.read_text(encoding="utf-8") if PAGE_PATH.exists() else ""
        if current != content:
            print(
                f"{PAGE_PATH.relative_to(ROOT_DIR)} is out of date; run"
                " python scripts/generate_plans_docs.py",
                file=sys.stderr,
            )
            return 1
        return 0
    PAGE_PATH.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

@dataclass(frozen=True, slots=True)
class Component:
    """One third-party package and the license texts it ships."""

    ecosystem: str
    name: str
    version: str
    license: str
    homepage: str
    author: str = ""
    texts: tuple[tuple[str, str], ...] = field(default_factory=tuple)


@dataclass(frozen=True, slots=True)
class Program:
    """A binary an image copies in outside the Python and Node.js packages."""

    name: str
    version: str
    license: str
    source: str
    images: str
    note: str = ""


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


# Package metadata spells the same license many ways; group them so a package
# without a license file can point at a reference text of the same license.
_LICENSE_KEYS = {
    "apache software license": "Apache-2.0",
    "apache 2.0": "Apache-2.0",
    "apache-2.0": "Apache-2.0",
    "apache license 2.0": "Apache-2.0",
    "mit license": "MIT",
    "mit": "MIT",
    "isc": "ISC",
    "isc license (iscl)": "ISC",
    "bsd-3-clause": "BSD-3-Clause",
    "bsd-2-clause": "BSD-2-Clause",
    "bsd license": "BSD-3-Clause",
    "bsd": "BSD-3-Clause",
    "mit or apache-2.0": "MIT",
    "psf-2.0": "PSF-2.0",
}


def license_key(license_id: str) -> str:
    """Return a normalised key for grouping equivalent license spellings."""
    return _LICENSE_KEYS.get(license_id.strip().lower(), license_id.strip())


def _clean_text(text: str) -> str:
    # Strip trailing whitespace so the repo's pre-commit hooks leave the file alone.
    lines = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    return "\n".join(line.rstrip() for line in lines).strip()


def python_requirements() -> list[tuple[str, str]]:
    """Return (name, version) for the workspace's production Python deps."""
    out = subprocess.run(
        [
            "uv",
            "export",
            "--no-dev",
            "--all-packages",
            "--format",
            "requirements-txt",
            "--no-hashes",
            "--no-emit-workspace",
            "--frozen",
            "-q",
        ],
        cwd=REPO,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    reqs: dict[str, tuple[str, str]] = {}
    for line in out.splitlines():
        match = re.match(
            r"^([A-Za-z0-9][A-Za-z0-9._\-]*)(\[[^\]]*\])?==([^\s;]+)", line
        )
        _, _, marker = line.partition(";")
        if marker.strip() and not any(
            Marker(marker.strip()).evaluate(env) for env in IMAGE_MARKER_ENVS
        ):
            continue
        if match:
            name, version = match.group(1), match.group(3)
            reqs[_norm(name)] = (name, version)
    return sorted(reqs.values(), key=lambda r: _norm(r[0]))


def _python_license(meta: md.PackageMetadata) -> str:
    if expr := meta.get("License-Expression"):
        return expr.strip()
    classifiers = [
        c.split("::")[-1].strip()
        for c in meta.get_all("Classifier") or []
        if c.startswith("License ::") and c != "License :: OSI Approved"
    ]
    if classifiers:
        return " / ".join(classifiers)
    raw = (meta.get("License") or "").strip().splitlines()
    return raw[0][:120] if raw else "See license text"


def _python_homepage(meta: md.PackageMetadata) -> str:
    if home := meta.get("Home-page"):
        return home
    for entry in meta.get_all("Project-URL") or []:
        label, _, url = entry.partition(",")
        if label.strip().lower() in {"homepage", "source", "repository", "source code"}:
            return url.strip()
    for entry in meta.get_all("Project-URL") or []:
        return entry.partition(",")[2].strip()
    return ""


def python_components() -> tuple[list[Component], list[str]]:
    """Collect Python components; returns (components, missing_names)."""
    components: list[Component] = []
    missing: list[str] = []
    for name, version in python_requirements():
        try:
            dist = md.distribution(name)
        except md.PackageNotFoundError:
            missing.append(f"{name}=={version}")
            continue
        if dist.version != version:
            missing.append(f"{name}=={version} (installed {dist.version})")
            continue
        texts: list[tuple[str, str]] = []
        for file in sorted(dist.files or [], key=str):
            rel = str(file)
            if ".dist-info/" not in rel or not LICENSE_FILE_RE.search(rel):
                continue
            if SKIP_FILE_RE.search(rel):
                continue
            path = Path(dist.locate_file(file))
            if path.is_file():
                texts.append(
                    (
                        rel.split(".dist-info/", 1)[1],
                        _clean_text(path.read_text(errors="replace")),
                    )
                )
        components.append(
            Component(
                ecosystem="python",
                name=dist.metadata["Name"],
                version=version,
                license=_python_license(dist.metadata),
                homepage=_python_homepage(dist.metadata),
                author=(
                    dist.metadata.get("Author")
                    or dist.metadata.get("Author-email")
                    or ""
                ).strip(),
                texts=tuple(texts),
            )
        )
    return components, missing


def frontend_components() -> list[Component]:
    """Collect production frontend packages from pnpm."""
    out = subprocess.run(
        ["pnpm", "licenses", "list", "--prod", "--json"],
        cwd=FRONTEND,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    data: dict[str, list[dict]] = json.loads(out)
    components: list[Component] = []
    for license_id, packages in data.items():
        for pkg in packages:
            for version, path_str in zip(pkg["versions"], pkg["paths"], strict=True):
                path = Path(path_str)
                texts: list[tuple[str, str]] = []
                if path.is_dir():
                    for child in sorted(path.iterdir()):
                        if (
                            child.is_file()
                            and LICENSE_FILE_RE.search(child.name)
                            and not SKIP_FILE_RE.search(child.name)
                        ):
                            texts.append(
                                (
                                    child.name,
                                    _clean_text(child.read_text(errors="replace")),
                                )
                            )
                components.append(
                    Component(
                        ecosystem="frontend",
                        name=pkg["name"],
                        version=version,
                        license=license_id,
                        homepage=pkg.get("homepage") or "",
                        author=(pkg.get("author") or "").strip(),
                        texts=tuple(texts),
                    )
                )
    return sorted(
        _for_ui_targets(components, _lockfile_platforms()),
        key=lambda c: (c.name.lower(), c.version),
    )


def _split_package_key(key: str) -> tuple[str, str]:
    """Split a pnpm-lock key such as `@img/sharp-linux-x64@0.35.5(peer)`."""
    key = key.split("(", 1)[0]
    name, _, version = key.rpartition("@")
    return name, version


def _lockfile_platforms() -> dict[tuple[str, str], dict[str, list[str]]]:
    """Return the os/cpu/libc constraints of every locked frontend package."""
    lock = yaml.safe_load(FRONTEND_LOCKFILE.read_text())
    platforms: dict[tuple[str, str], dict[str, list[str]]] = {}
    for key, entry in (lock.get("packages") or {}).items():
        constraints = {
            field_name: [str(v) for v in entry[field_name]]
            for field_name in ("os", "cpu", "libc")
            if entry.get(field_name)
        }
        platforms[_split_package_key(key)] = constraints
    return platforms


def _allows(values: list[str] | None, targets: frozenset[str]) -> bool:
    """Evaluate an npm os/cpu/libc list, including `!value` exclusions."""
    if not values:
        return True
    excluded = {v[1:] for v in values if v.startswith("!")}
    included = {v for v in values if not v.startswith("!")}
    if included:
        return bool((included & targets) - excluded)
    return bool(targets - excluded)


def _matches_ui_targets(constraints: dict[str, list[str]]) -> bool:
    return (
        _allows(constraints.get("os"), UI_TARGET_OS)
        and _allows(constraints.get("cpu"), UI_TARGET_CPU)
        and _allows(constraints.get("libc"), UI_TARGET_LIBC)
    )


def frontend_requirements() -> list[tuple[str, str]]:
    """Return (name, version) of every production package the UI image ships.

    Read from `pnpm-lock.yaml` alone, so it needs neither `pnpm install` nor
    the network: walk the production and optional dependencies of the frontend
    importer, skipping native variants the UI targets never install and
    everything reachable only through them.
    """
    lock = yaml.safe_load(FRONTEND_LOCKFILE.read_text())
    importer = (lock.get("importers") or {}).get(".") or {}
    snapshots: dict[str, dict] = lock.get("snapshots") or {}
    platforms = _lockfile_platforms()
    pending = [
        f"{name}@{entry['version']}"
        for section in ("dependencies", "optionalDependencies")
        for name, entry in (importer.get(section) or {}).items()
        if not str(entry["version"]).startswith("link:")
    ]
    seen: set[str] = set()
    shipped: dict[tuple[str, str], tuple[str, str]] = {}
    while pending:
        key = pending.pop()
        if key in seen:
            continue
        seen.add(key)
        name, version = _split_package_key(key)
        if name in WASM_ONLY_PACKAGES or not _matches_ui_targets(
            platforms.get((name, version), {})
        ):
            continue
        shipped[(_norm(name), version)] = (name, version)
        snapshot = snapshots.get(key) or {}
        for section in ("dependencies", "optionalDependencies"):
            for dep, dep_version in (snapshot.get(section) or {}).items():
                if not str(dep_version).startswith("link:"):
                    pending.append(f"{dep}@{dep_version}")
    return sorted(shipped.values(), key=lambda r: (_norm(r[0]), r[1]))


_PACKAGE_ROW_RE = re.compile(r"^\| (\S+) \| (\S+) \| .* \|$")


def notice_packages(path: Path) -> set[tuple[str, str]]:
    """(normalized name, version) of each row in a notices file's package table."""
    rows: set[tuple[str, str]] = set()
    in_table = False
    for line in path.read_text().splitlines():
        if line == "| Package | Version | License |":
            in_table = True
            continue
        if in_table:
            if line.startswith("|---"):
                continue
            match = _PACKAGE_ROW_RE.match(line)
            if match is None:
                break
            rows.add((_norm(match.group(1)), match.group(2)))
    return rows


def lockfile_drift() -> list[str]:
    """Describe every difference between the notices and the lockfiles.

    Compares package names and versions only, so it runs offline and without
    installed packages. `--check` additionally compares license texts, which
    needs `uv sync` and `pnpm install`.
    """
    problems: list[str] = []
    for output, requirements in (
        (PYTHON_OUTPUT, python_requirements()),
        (FRONTEND_OUTPUT, frontend_requirements()),
    ):
        relative = output.relative_to(REPO)
        if not output.exists():
            problems.append(f"{relative} is missing")
            continue
        listed = notice_packages(output)
        locked = {(_norm(name), version) for name, version in requirements}
        problems.extend(
            f"{relative} is missing {name} {version}"
            for name, version in sorted(locked - listed)
        )
        problems.extend(
            f"{relative} lists {name} {version}, which the lockfile no longer ships"
            for name, version in sorted(listed - locked)
        )
    return problems



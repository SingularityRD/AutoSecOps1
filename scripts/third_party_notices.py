"""Generate the third-party notices shipped in the AutoSecOps images.

    uv run python scripts/third_party_notices.py          # rewrite the file
    uv run python scripts/third_party_notices.py --check  # exit 1 if it is stale
    python scripts/third_party_notices.py --check-lockfiles  # offline drift check

Writes `THIRD_PARTY_NOTICES.md` (Python, for the API and tunnel-gateway
images) and `frontend/THIRD_PARTY_NOTICES.md` (for the UI image), covering
production dependencies only:

- Python: `uv export --no-dev` for the workspace, with license texts read from
  the installed distributions in the current environment (run `uv sync` first).
- Frontend: `pnpm licenses list --prod --json` in `frontend/`, with license
  texts read from each package directory (run `pnpm install` first). pnpm only
  installs native packages for the build host, so platform-specific packages
  are swapped for the UI image's targets (Linux musl on x64 and arm64) from
  `pnpm-lock.yaml`, with license texts taken from the installed host variant.
- Bundled programs: binaries the Dockerfiles copy in outside both package
  managers (Python and Node.js runtimes, nsjail, uv, DuckDB, the Pangolin CLI),
  with versions read from the Dockerfiles.

The output depends only on the lockfiles and Dockerfiles, not on the platform
that runs this script.

MIT, BSD, Apache and similar licenses require their copyright notices to ship
with the software, and the bundled frontend strips them from the code, so this
file carries them instead.
"""


def _native_family(name: str) -> str:
    """Name without platform tokens: `@img/sharp-linuxmusl-x64` -> `@img/sharp`."""
    scope, _, base = name.rpartition("/")
    kept = [part for part in base.split("-") if part not in _PLATFORM_TOKENS]
    return f"{scope}/{'-'.join(kept)}" if scope else "-".join(kept)


def _for_ui_targets(
    components: list[Component],
    platforms: dict[tuple[str, str], dict[str, list[str]]],
) -> list[Component]:
    """Swap the build host's native packages for the UI image's targets.

    pnpm installs the native variant for the host only, e.g.
    `@img/sharp-linux-x64` on glibc x64. The image ships the musl variants for
    x64 and arm64 instead, which share version, license and license text with
    the host variant of the same family.
    """
    installed = {(c.name, c.version) for c in components}
    kept = [
        c
        for c in components
        if _matches_ui_targets(platforms.get((c.name, c.version), {}))
    ]
    # One installed variant per native family and version supplies the
    # license and texts for the target variants.
    host_variants: dict[tuple[str, str], Component] = {}
    for c in sorted(components, key=lambda c: c.name):
        if platforms.get((c.name, c.version)):
            host_variants.setdefault((_native_family(c.name), c.version), c)
    for (name, version), constraints in sorted(platforms.items()):
        if (name, version) in installed or not constraints:
            continue
        if not _matches_ui_targets(constraints):
            continue
        host = host_variants.get((_native_family(name), version))
        if host is None:
            # Not a variant of a native package in the production tree.
            continue
        kept.append(
            Component(
                ecosystem="frontend",
                name=name,
                version=version,
                license=host.license,
                homepage=host.homepage,
                author=host.author,
                texts=host.texts,
            )
        )
    return kept


def _dockerfile_value(dockerfile: str, pattern: str) -> str:
    text = (REPO / dockerfile).read_text()
    match = re.search(pattern, text, re.MULTILINE)
    if match is None:
        raise ValueError(f"{dockerfile}: no match for {pattern!r}")
    return match.group(1)



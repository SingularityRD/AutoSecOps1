def _render_programs(programs: list[Program]) -> list[str]:
    if not programs:
        return []
    parts = [f"\n## Bundled programs ({len(programs)})\n"]
    parts.append("| Program | Version | License | Images |\n|---|---|---|---|")
    parts.extend(
        f"| {p.name} | {p.version} | {p.license} | {p.images} |" for p in programs
    )
    parts.append("")
    for p in programs:
        parts.append(f"### {p.name} {p.version}\n")
        parts.append(
            f"- License: {p.license}\n- Source: {p.source}"
            + (f"\n- {p.note}" if p.note else "")
            + "\n"
        )
    return parts


def render(title: str, components: list[Component], programs: list[Program]) -> str:
    parts = [HEADER, f"\n## {title} ({len(components)})\n"]
    parts.append("| Package | Version | License |\n|---|---|---|")
    parts.extend(
        f"| {c.name} | {c.version} | {c.license.replace('|', '/')} |"
        for c in components
    )
    parts.append("\n## License texts\n")
    for c in components:
        parts.append(f"### {c.name} {c.version}\n")
        parts.append(
            f"- License: {c.license}"
            + (f"\n- Homepage: {c.homepage}" if c.homepage else "")
            + "\n"
        )
        if not c.texts:
            holder = c.author or "the package authors"
            parts.append(
                f"No license file ships with this package. Copyright holder: {holder}. "
                f"The license text is in the appendix under {license_key(c.license)}.\n"
            )
        for fname, text in c.texts:
            parts.append(f"`{fname}`:\n\n```text\n{text}\n```\n")
    parts.extend(_render_programs(programs))
    parts.extend(_appendix(components, programs))
    return "\n".join(parts).rstrip() + "\n"


def _appendix(components: list[Component], programs: list[Program]) -> list[str]:
    """Reference texts for licenses of packages that ship no license file."""
    needed = sorted(
        {license_key(c.license) for c in components if not c.texts}
        | {license_key(p.license) for p in programs}
    )
    if not needed:
        return []
    parts = ["\n## Appendix: license texts for components without a license file\n"]
    for key in needed:
        reference = next(
            (c for c in components if c.texts and license_key(c.license) == key),
            None,
        )
        parts.append(f"### {key}\n")
        if reference is None:
            parts.append(f"Standard text: https://spdx.org/licenses/{key}.html\n")
            continue
        fname, text = reference.texts[0]
        parts.append(
            f"Reference text as shipped by {reference.name} {reference.version} (`{fname}`). "
            "For each package above, the copyright holder named with it replaces the copyright line.\n"
        )
        parts.append(f"```text\n{text}\n```\n")
    return parts


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--check", action="store_true", help="exit 1 if a notices file is stale"
    )
    parser.add_argument(
        "--check-lockfiles",
        action="store_true",
        help=(
            "exit 1 if the package lists differ from uv.lock or pnpm-lock.yaml "
            "(offline; needs no installed packages)"
        ),
    )
    args = parser.parse_args()

    if args.check_lockfiles:
        problems = lockfile_drift()
        for problem in problems:
            print(problem, file=sys.stderr)
        if problems:
            print(
                "run `just gen-notices` and commit the regenerated notices; "
                "for a Dependabot pull request, see Dependencies in "
                "CONTRIBUTING.md",
                file=sys.stderr,
            )
            return 1
        print("third-party notices match the lockfiles")
        return 0

    python, missing = python_components()
    if missing:
        print(
            "Not installed at the locked version (run `uv sync --all-packages`):",
            file=sys.stderr,
        )
        for item in missing:
            print(f"  {item}", file=sys.stderr)
        return 2
    outputs = {
        PYTHON_OUTPUT: render("Python packages", python, api_programs()),
        FRONTEND_OUTPUT: render(
            "Frontend packages", frontend_components(), ui_programs()
        ),
    }

    if args.check:
        stale = [
            p
            for p, content in outputs.items()
            if not p.exists() or p.read_text() != content
        ]
        for path in stale:
            print(
                f"{path.relative_to(REPO)} is stale; run `uv run python scripts/third_party_notices.py`",
                file=sys.stderr,
            )
        if stale:
            return 1
        print("third-party notices are up to date")
        return 0
    for path, content in outputs.items():
        path.write_text(content)
        print(
            f"wrote {path.relative_to(REPO)} ({content.count(chr(10) + '### ')} entries)"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

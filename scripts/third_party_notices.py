REPO = Path(__file__).resolve().parents[1]
FRONTEND = REPO / "frontend"
# The API and tunnel-gateway images build from the repo root, the UI image from
# frontend/, so each image gets the notices for what it ships.
PYTHON_OUTPUT = REPO / "THIRD_PARTY_NOTICES.md"
FRONTEND_OUTPUT = FRONTEND / "THIRD_PARTY_NOTICES.md"

# The images are Linux on x86_64 and arm64; Windows-only markers in the
# lockfile must not count. A requirement ships if any target platform needs it.
IMAGE_MARKER_ENVS = tuple(
    {
        "sys_platform": "linux",
        "platform_system": "Linux",
        "os_name": "posix",
        "platform_machine": machine,
        "python_version": "3.12",
        "python_full_version": "3.12.0",
        "implementation_name": "cpython",
        "platform_python_implementation": "CPython",
    }
    for machine in ("x86_64", "aarch64")
)

# frontend/Dockerfile.prod installs native packages for these targets only
# (`pnpm.supportedArchitectures`).
UI_TARGET_OS = frozenset({"linux"})
UI_TARGET_CPU = frozenset({"x64", "arm64"})
UI_TARGET_LIBC = frozenset({"musl"})
FRONTEND_LOCKFILE = FRONTEND / "pnpm-lock.yaml"
# Optional packages whose package.json restricts `cpu` to WebAssembly. pnpm
# never installs them for the UI image, but pnpm-lock.yaml does not record
# their `cpu` field, so the offline lockfile walk names them here.
WASM_ONLY_PACKAGES = frozenset({"@img/sharp-wasm32"})

LICENSE_FILE_RE = re.compile(
    r"(^|/)(licen[cs]e|copying|notice|copyright|unlicense)([.\-_][^/]*)?$",
    re.IGNORECASE,
)
# Generated build metadata, not license text.
SKIP_FILE_RE = re.compile(r"\.(py|pyc|js|ts|json|html|tsx?)$", re.IGNORECASE)


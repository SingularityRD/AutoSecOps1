"""Generate the third-party notices shipped in the AutoSecOps images.

    uv run python scripts/third_party_notices.py          # rewrite the file
    uv run python scripts/third_party_notices.py --check  # exit 1 if it is stale

Writes `THIRD_PARTY_NOTICES.md` (Python, for the API and tunnel-gateway
images) and `frontend/THIRD_PARTY_NOTICES.md` (for the UI image), covering
production dependencies only:

- Python: `uv export --no-dev` for the workspace, with license texts read from
  the installed distributions in the current environment (run `uv sync` first).
- Frontend: `pnpm licenses list --prod --json` in `frontend/`, with license
  texts read from each package directory (run `pnpm install` first).

MIT, BSD, Apache and similar licenses require their copyright notices to ship
with the software, and the bundled frontend strips them from the code, so this
file carries them instead.
"""

from __future__ import annotations

import argparse
import importlib.metadata as md
import json
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

from packaging.markers import Marker

REPO = Path(__file__).resolve().parents[1]
FRONTEND = REPO / "frontend"
# The API and tunnel-gateway images build from the repo root, the UI image from
# frontend/, so each image gets the notices for what it ships.
PYTHON_OUTPUT = REPO / "THIRD_PARTY_NOTICES.md"
FRONTEND_OUTPUT = FRONTEND / "THIRD_PARTY_NOTICES.md"

# The images are Linux; Windows-only markers in the lockfile must not count.
IMAGE_MARKER_ENV = {
    "sys_platform": "linux",
    "platform_system": "Linux",
    "os_name": "posix",
    "platform_machine": "x86_64",
    "python_version": "3.12",
    "python_full_version": "3.12.0",
    "implementation_name": "cpython",
    "platform_python_implementation": "CPython",
}

LICENSE_FILE_RE = re.compile(
    r"(^|/)(licen[cs]e|copying|notice|copyright|unlicense)([.\-_][^/]*)?$",
    re.IGNORECASE,
)
# Generated build metadata, not license text.
SKIP_FILE_RE = re.compile(r"\.(py|pyc|js|ts|json|html|tsx?)$", re.IGNORECASE)

HEADER = """# Third-party notices

AutoSecOps is proprietary software of SingularityRD (see `LICENSE`). It includes
the third-party open source components listed below. Each component is
distributed under its own license, reproduced here as shipped by the component.
Nothing in the AutoSecOps license restricts rights granted by these licenses.

Components under the LGPL (for example psycopg, paramiko, chardet, ldap3 and
libvips via sharp in the UI image) are used unmodified as separately loadable libraries and can
be replaced by the user. ansible-core (GPL-3.0-or-later) is invoked by the
Ansible integration as a separate program through ansible-runner; its complete
source is included in the image as installed Python files. Where a component is
offered under a choice of licenses, AutoSecOps uses it under the permissive
option (for example DOMPurify under Apache-2.0, text-unidecode under the
Artistic License).

Operating system packages in the container base images carry their own notices
under `/usr/share/doc/*/copyright`. The Node.js runtime in the API image is
distributed under the MIT license (https://github.com/nodejs/node/blob/main/LICENSE). Vendored agent skills and data files keep
their license files next to them in the source tree.

This file is generated by `scripts/third_party_notices.py`. Do not edit it by
hand.
"""


@dataclass(frozen=True, slots=True)
class Component:
    """One third-party package and the license texts it ships."""

    ecosystem: str
    name: str
    version: str
    license: str
    homepage: str
    author: str = ""
    texts: tuple[tuple[str, str], ...] = field(default_factory=tuple)


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


# Package metadata spells the same license many ways; group them so a package
# without a license file can point at a reference text of the same license.
_LICENSE_KEYS = {
    "apache software license": "Apache-2.0",
    "apache 2.0": "Apache-2.0",
    "apache-2.0": "Apache-2.0",
    "apache license 2.0": "Apache-2.0",
    "mit license": "MIT",
    "mit": "MIT",
    "isc": "ISC",
    "isc license (iscl)": "ISC",
    "bsd-3-clause": "BSD-3-Clause",
    "bsd-2-clause": "BSD-2-Clause",
    "bsd license": "BSD-3-Clause",
    "bsd": "BSD-3-Clause",
}


def license_key(license_id: str) -> str:
    """Return a normalised key for grouping equivalent license spellings."""
    return _LICENSE_KEYS.get(license_id.strip().lower(), license_id.strip())


def _clean_text(text: str) -> str:
    # Strip trailing whitespace so the repo's pre-commit hooks leave the file alone.
    lines = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    return "\n".join(line.rstrip() for line in lines).strip()


def python_requirements() -> list[tuple[str, str]]:
    """Return (name, version) for the workspace's production Python deps."""
    out = subprocess.run(
        [
            "uv",
            "export",
            "--no-dev",
            "--all-packages",
            "--format",
            "requirements-txt",
            "--no-hashes",
            "--no-emit-workspace",
            "--frozen",
            "-q",
        ],
        cwd=REPO,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    reqs: dict[str, tuple[str, str]] = {}
    for line in out.splitlines():
        match = re.match(
            r"^([A-Za-z0-9][A-Za-z0-9._\-]*)(\[[^\]]*\])?==([^\s;]+)", line
        )
        _, _, marker = line.partition(";")
        if marker.strip() and not Marker(marker.strip()).evaluate(IMAGE_MARKER_ENV):
            continue
        if match:
            name, version = match.group(1), match.group(3)
            reqs[_norm(name)] = (name, version)
    return sorted(reqs.values(), key=lambda r: _norm(r[0]))


def _python_license(meta: md.PackageMetadata) -> str:
    if expr := meta.get("License-Expression"):
        return expr.strip()
    classifiers = [
        c.split("::")[-1].strip()
        for c in meta.get_all("Classifier") or []
        if c.startswith("License ::") and c != "License :: OSI Approved"
    ]
    if classifiers:
        return " / ".join(classifiers)
    raw = (meta.get("License") or "").strip().splitlines()
    return raw[0][:120] if raw else "See license text"


def _python_homepage(meta: md.PackageMetadata) -> str:
    if home := meta.get("Home-page"):
        return home
    for entry in meta.get_all("Project-URL") or []:
        label, _, url = entry.partition(",")
        if label.strip().lower() in {"homepage", "source", "repository", "source code"}:
            return url.strip()
    for entry in meta.get_all("Project-URL") or []:
        return entry.partition(",")[2].strip()
    return ""


def python_components() -> tuple[list[Component], list[str]]:
    """Collect Python components; returns (components, missing_names)."""
    components: list[Component] = []
    missing: list[str] = []
    for name, version in python_requirements():
        try:
            dist = md.distribution(name)
        except md.PackageNotFoundError:
            missing.append(f"{name}=={version}")
            continue
        if dist.version != version:
            missing.append(f"{name}=={version} (installed {dist.version})")
            continue
        texts: list[tuple[str, str]] = []
        for file in sorted(dist.files or [], key=str):
            rel = str(file)
            if ".dist-info/" not in rel or not LICENSE_FILE_RE.search(rel):
                continue
            if SKIP_FILE_RE.search(rel):
                continue
            path = Path(dist.locate_file(file))
            if path.is_file():
                texts.append(
                    (
                        rel.split(".dist-info/", 1)[1],
                        _clean_text(path.read_text(errors="replace")),
                    )
                )
        components.append(
            Component(
                ecosystem="python",
                name=dist.metadata["Name"],
                version=version,
                license=_python_license(dist.metadata),
                homepage=_python_homepage(dist.metadata),
                author=(
                    dist.metadata.get("Author")
                    or dist.metadata.get("Author-email")
                    or ""
                ).strip(),
                texts=tuple(texts),
            )
        )
    return components, missing


def frontend_components() -> list[Component]:
    """Collect production frontend packages from pnpm."""
    out = subprocess.run(
        ["pnpm", "licenses", "list", "--prod", "--json"],
        cwd=FRONTEND,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    data: dict[str, list[dict]] = json.loads(out)
    components: list[Component] = []
    for license_id, packages in data.items():
        for pkg in packages:
            for version, path_str in zip(pkg["versions"], pkg["paths"], strict=True):
                path = Path(path_str)
                texts: list[tuple[str, str]] = []
                if path.is_dir():
                    for child in sorted(path.iterdir()):
                        if (
                            child.is_file()
                            and LICENSE_FILE_RE.search(child.name)
                            and not SKIP_FILE_RE.search(child.name)
                        ):
                            texts.append(
                                (
                                    child.name,
                                    _clean_text(child.read_text(errors="replace")),
                                )
                            )
                components.append(
                    Component(
                        ecosystem="frontend",
                        name=pkg["name"],
                        version=version,
                        license=license_id,
                        homepage=pkg.get("homepage") or "",
                        author=(pkg.get("author") or "").strip(),
                        texts=tuple(texts),
                    )
                )
    return sorted(components, key=lambda c: (c.name.lower(), c.version))


def render(title: str, components: list[Component]) -> str:
    parts = [HEADER, f"\n## {title} ({len(components)})\n"]
    parts.append("| Package | Version | License |\n|---|---|---|")
    parts.extend(
        f"| {c.name} | {c.version} | {c.license.replace('|', '/')} |"
        for c in components
    )
    parts.append("\n## License texts\n")
    for c in components:
        parts.append(f"### {c.name} {c.version}\n")
        parts.append(
            f"- License: {c.license}"
            + (f"\n- Homepage: {c.homepage}" if c.homepage else "")
            + "\n"
        )
        if not c.texts:
            holder = c.author or "the package authors"
            parts.append(
                f"No license file ships with this package. Copyright holder: {holder}. "
                f"The license text is in the appendix under {license_key(c.license)}.\n"
            )
        for fname, text in c.texts:
            parts.append(f"`{fname}`:\n\n```text\n{text}\n```\n")
    parts.extend(_appendix(components))
    return "\n".join(parts).rstrip() + "\n"


def _appendix(components: list[Component]) -> list[str]:
    """Reference texts for licenses of packages that ship no license file."""
    needed = sorted({license_key(c.license) for c in components if not c.texts})
    if not needed:
        return []
    parts = ["\n## Appendix: license texts for packages without a license file\n"]
    for key in needed:
        reference = next(
            (c for c in components if c.texts and license_key(c.license) == key),
            None,
        )
        parts.append(f"### {key}\n")
        if reference is None:
            parts.append(f"Standard text: https://spdx.org/licenses/{key}.html\n")
            continue
        fname, text = reference.texts[0]
        parts.append(
            f"Reference text as shipped by {reference.name} {reference.version} (`{fname}`). "
            "For each package above, the copyright holder named with it replaces the copyright line.\n"
        )
        parts.append(f"```text\n{text}\n```\n")
    return parts


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--check", action="store_true", help="exit 1 if a notices file is stale"
    )
    args = parser.parse_args()

    python, missing = python_components()
    if missing:
        print(
            "Not installed at the locked version (run `uv sync --all-packages`):",
            file=sys.stderr,
        )
        for item in missing:
            print(f"  {item}", file=sys.stderr)
        return 2
    outputs = {
        PYTHON_OUTPUT: render("Python packages", python),
        FRONTEND_OUTPUT: render("Frontend packages", frontend_components()),
    }

    if args.check:
        stale = [
            p
            for p, content in outputs.items()
            if not p.exists() or p.read_text() != content
        ]
        for path in stale:
            print(
                f"{path.relative_to(REPO)} is stale; run `uv run python scripts/third_party_notices.py`",
                file=sys.stderr,
            )
        if stale:
            return 1
        print("third-party notices are up to date")
        return 0
    for path, content in outputs.items():
        path.write_text(content)
        print(
            f"wrote {path.relative_to(REPO)} ({content.count(chr(10) + '### ')} entries)"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
